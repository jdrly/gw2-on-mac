#!/usr/bin/env python3
# Turns the Lucide icons in app/src/icons/*.svg (lucide-static, ISC, see LICENSE.txt there) into
# app/src/native/LucideData.swift: each icon's shapes as SVG path data in its 24 x 24 box, which
# Lucide.swift parses and strokes like Lucide does (width 2, round caps and joins). Circles,
# rects, lines, polylines and polygons become path data here; arcs stay arcs.
#
#   python3 -I app/scripts/gen-icons.py      (after adding or changing an icon)
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
ICONS = ROOT / "src" / "icons"
OUT = ROOT / "src" / "native" / "LucideData.swift"


def num(v):
    return float(v) if v is not None else 0.0


def fmt(x):
    s = ("%.3f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def shape_to_d(tag, a):
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a.get("cx")), num(a.get("cy")), num(a.get("r"))
        return "M%s %sa%s %s 0 1 0 %s 0a%s %s 0 1 0 %s 0Z" % (
            fmt(cx - r), fmt(cy), fmt(r), fmt(r), fmt(2 * r), fmt(r), fmt(r), fmt(-2 * r))
    if tag == "ellipse":
        cx, cy, rx, ry = num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry"))
        return "M%s %sa%s %s 0 1 0 %s 0a%s %s 0 1 0 %s 0Z" % (
            fmt(cx - rx), fmt(cy), fmt(rx), fmt(ry), fmt(2 * rx), fmt(rx), fmt(ry), fmt(-2 * rx))
    if tag == "rect":
        x, y, w, h = num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height"))
        rx = a.get("rx")
        ry = a.get("ry")
        rx = num(rx if rx is not None else ry)
        ry = num(ry if ry is not None else rx)
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx == 0:
            return "M%s %sh%sv%sh%sZ" % (fmt(x), fmt(y), fmt(w), fmt(h), fmt(-w))
        return ("M%s %sh%sa%s %s 0 0 1 %s %sv%sa%s %s 0 0 1 %s %sh%sa%s %s 0 0 1 %s %sv%sa%s %s 0 0 1 %s %sZ" % (
            fmt(x + rx), fmt(y), fmt(w - 2 * rx), fmt(rx), fmt(ry), fmt(rx), fmt(ry), fmt(h - 2 * ry),
            fmt(rx), fmt(ry), fmt(-rx), fmt(ry), fmt(-(w - 2 * rx)), fmt(rx), fmt(ry), fmt(-rx), fmt(-ry),
            fmt(-(h - 2 * ry)), fmt(rx), fmt(ry), fmt(rx), fmt(-ry)))
    if tag == "line":
        return "M%s %sL%s %s" % tuple(fmt(num(a.get(k))) for k in ("x1", "y1", "x2", "y2"))
    if tag in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        pairs = [(pts[i], pts[i + 1]) for i in range(0, len(pts) - 1, 2)]
        d = "M" + " L".join("%s %s" % p for p in pairs)
        return d + ("Z" if tag == "polygon" else "")
    raise SystemExit("unsupported element <%s>" % tag)


def main():
    icons = {}
    for svg in sorted(ICONS.glob("*.svg")):
        tree = ET.parse(svg)
        ds = []
        for el in tree.getroot().iter():
            tag = el.tag.split("}")[-1]
            if tag in ("svg", "g", "title", "desc"):
                continue
            ds.append(shape_to_d(tag, el.attrib))
        icons[svg.stem] = ds
    lines = [
        "// Generated by app/scripts/gen-icons.py from app/src/icons/*.svg (Lucide, lucide-static",
        "// 0.460.0, ISC license: app/src/icons/LICENSE.txt). Don't edit; run the script again.",
        "",
        "enum LucideData {",
        "  static let paths: [String: [String]] = [",
    ]
    for name, ds in icons.items():
        body = ", ".join('"%s"' % d.replace('"', '') for d in ds)
        lines.append('    "%s": [%s],' % (name, body))
    lines += ["  ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print("wrote %s (%d icons)" % (OUT, len(icons)), file=sys.stderr)


main()
